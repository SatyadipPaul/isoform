/**
 * Bundle the viewer into a single inlinable string.
 *
 * `exportHtml` promises a file that opens with no network — so three.js and the
 * viewer have to be *inside* it, which means the library must carry a prebuilt,
 * self-contained copy of them as text.
 *
 * The output is a plain ES module exporting one string constant rather than a
 * `.ts` file: a ~700 kB string literal is something TypeScript would parse on
 * every build for no benefit, and nothing here needs type checking. A
 * hand-written `.d.ts` beside it gives the import its type.
 *
 * Imported dynamically by `export/html.ts`, so a bundler can split it out and
 * anyone who never calls `exportHtml` never downloads it.
 */

import { build } from 'vite'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = resolve(root, 'packages/isoform')

/**
 * Written to `src/` *and* `dist/`.
 *
 * `tsc` compiles TypeScript and copies nothing else, so a generated `.js` beside
 * the sources never reaches the emitted package — `dist/export/html.js` would
 * import `../generated/viewer-runtime.js` and find nothing. That failure is
 * invisible in this repo, where `src/` always has it, and appears only once
 * somebody installs the package and calls `exportHtml`.
 *
 * `src/` is what dev and the test suite import; `dist/` is what ships.
 */
const outDirs = [resolve(pkg, 'src/generated'), resolve(pkg, 'dist/generated')]

const result = await build({
  root: pkg,
  configFile: false,
  logLevel: 'warn',
  build: {
    write: false,
    /* IIFE, not ESM: the exported page inlines this into a plain `<script>`,
       and a module script is subject to CORS rules that a `file://` page fails. */
    lib: { entry: resolve(pkg, 'src/export/runtime-entry.ts'), formats: ['iife'], name: 'IsoformRuntime' },
    /* `true`, not `'esbuild'`: Vite 8 minifies with oxc and treats the esbuild
       path as deprecated, requiring a separate install that this repo does not
       have. */
    minify: true,
    target: 'es2020',
    /* three is bundled in on purpose. It is a peer dependency for consumers of
       the library, but an exported file has no package manager to resolve it. */
    rollupOptions: { external: [] },
  },
})

const chunks = (Array.isArray(result) ? result[0] : result).output
const code = chunks.find((c) => c.type === 'chunk' && c.isEntry)?.code
if (!code) throw new Error('build-viewer-runtime: no entry chunk produced')

const js = `/* Generated by scripts/build-viewer-runtime.mjs — do not edit. */\nexport default ${JSON.stringify(code)}\n`
const dts = `/** The viewer bundled as standalone IIFE source, for inlining into an export. */\ndeclare const runtime: string\nexport default runtime\n`

for (const dir of outDirs) {
  mkdirSync(dir, { recursive: true })
  writeFileSync(resolve(dir, 'viewer-runtime.js'), js)
  writeFileSync(resolve(dir, 'viewer-runtime.d.ts'), dts)
}

const kb = (n) => `${(n / 1024).toFixed(0)} kB`
console.log(
  `viewer runtime: ${kb(code.length)} → ${outDirs.length} locations ` +
    `(inlined into every exported HTML file)`,
)

/* A sanity floor. If this ever comes out tiny, three failed to bundle and every
   exported file would be a blank page that only fails once someone opens it. */
if (code.length < 200_000) {
  throw new Error(`build-viewer-runtime: suspiciously small (${kb(code.length)}) — did three bundle?`)
}
